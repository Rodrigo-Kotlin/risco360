export function validarBaseNR4(): {
  valida: boolean
  total: number
  conflitos: NR4Conflito[]
} {
  const visto = new Map<string, GrauRiscoNR4[]>()
  const descricoes = new Map<string, string[]>()

  for (const item of NR4_CNAE_GRAU_RISCO) {
    const existing = visto.get(item.cnae4) ?? []
    existing.push(item.grauRisco)
    visto.set(item.cnae4, existing)

    const existingDesc = descricoes.get(item.cnae4) ?? []
    if (item.descricao && !existingDesc.includes(item.descricao)) {
      existingDesc.push(item.descricao)
    }
    descricoes.set(item.cnae4, existingDesc)
  }

  const conflitos: NR4Conflito[] = []

  for (const [cnae4, graus] of visto) {
    const unique = [...new Set(graus)]
    if (unique.length > 1) {
      conflitos.push({
        cnae4,
        graus: unique as GrauRiscoNR4[],
        descricoes: descricoes.get(cnae4) ?? [],
        mensagem: `CNAE ${cnae4} possui ${unique.length} graus de risco diferentes: ${unique.join(', ')}. Revisão manual necessária.`,
      })
    }
  }

  return {
    valida: conflitos.length === 0,
    total: NR4_CNAE_GRAU_RISCO.length,
    conflitos,
  }
}

