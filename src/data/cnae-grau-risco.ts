function limparCnae(cnae: string): string {
  return cnae.replace(/[^\d]/g, '')
}

export function buscarGrauRiscoPorCnae(cnae: string): CnaeRisco | null {
  const cnaeLimpo = limparCnae(cnae)

  const encontrado = CNAE_RISCO_MAP.find((item) => {
    const itemLimpo = limparCnae(item.codigo)
    return cnaeLimpo.startsWith(itemLimpo)
  })

  if (encontrado) return encontrado

  const parcial = CNAE_RISCO_MAP.find((item) => {
    const itemLimpo = limparCnae(item.codigo)
    return cnaeLimpo.startsWith(itemLimpo.substring(0, 4))
  })

  return parcial ?? null
}

export function obterDescricaoGrauRisco(grau: number): string {
  const descricoes: Record<number, string> = {
    1: 'Grau 1 - Baixo',
    2: 'Grau 2 - Médio',
    3: 'Grau 3 - Alto',
    4: 'Grau 4 - Muito Alto',
  }
  return descricoes[grau] ?? `Grau ${grau}`
}

